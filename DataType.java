void main(){
    // byte
    byte num1=122;
    System.out.println(num1);

    //short
    short num2=198;
    System.out.println(num2);

    //int
    int num3=12876;
    System.out.println(num3);

    //long

    long num4=987654;
    System.out.println(num4);

    // floating point

    float num5=3.76f;
    System.out.println(num5);

    double num6=3.77723;
    System.out.println(num6);

    //char

    char firstcharacter = 'A';
    System.out.println("The firstcharacter is :" + (firstcharacter));
    System.out.println("The firstcharacter is :" + (firstcharacter+2));
    System.out.println("The firstcharacter is :" + (char)(firstcharacter));
}